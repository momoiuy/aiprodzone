/**
 * دالة مساعدة لتوفير قيم ذكية تلقائية لحقول GEO و SEO في حال غيابها
 * تضمن عدم انكسار أي مقال قديم أو أي اختبار
 */
export function resolveArticleGeoSeo(article) {
  if (!article) return null;

  const definitionLead =
    article.definitionLead ||
    (article.summary
      ? article.summary.split(/[.!\n]/)[0].trim() + '.'
      : `${article.title}: دليل أكاديمي شامل من منصة AIProdZone.`);

  const quickTakeaways =
    article.quickTakeaways && article.quickTakeaways.length > 0
      ? article.quickTakeaways
      : article.keyTakeaways && article.keyTakeaways.length > 0
      ? article.keyTakeaways.slice(0, 4)
      : [
          `فهم الركائز الأساسية لـ ${article.title}`,
          'المقارنة المنهجية بين الخيارات المتاحة وأفضل الممارسات التقنية',
          'خارطة طريق عملية للربط بسوق العمل وبناء مشاريع إنتاجية',
          'تجنب الأخطاء الشائعة وحل المشكلات الهندسية بكفاءة'
        ];

  const comparisonTable =
    article.comparisonTable ||
    (() => {
      const secWithTable = (article.sections || []).find(
        (s) => s.table && s.table.headers && s.table.rows
      );
      return secWithTable?.table || null;
    })();

  const faqs =
    article.faqs && article.faqs.length > 0
      ? article.faqs
      : [
          {
            question: `ما أهمية ${article.title ? article.title.split(/[:؟]/)[0].trim() : 'الموضوع'} في عام 2026؟`,
            answer: definitionLead
          },
          {
            question: 'كيف أبدأ دراسة هذا المسار وما هي المتطلبات السابقة؟',
            answer:
              article.summary ||
              'يوصى بالبدء بالتأسيس الأكاديمي والممارسة العملية وتطبيق المشاريع خطوة بخطوة.'
          },
          {
            question: 'ما هي أفضل الشروحات والمصادر الموصى بها في منصة AIProdZone؟',
            answer:
              'توفر المنصة مسارات منسقة ومرتبة معتمدة تغطي هذا المجال بالكامل مع ربط مباشر بالدورات ذات الصلة.'
          }
        ];

  const seoKeywords =
    article.seoKeywords && article.seoKeywords.length > 0
      ? article.seoKeywords
      : Array.from(
          new Set([...(article.tags || []), article.category, 'AIProdZone', 'تعلم البرمجة 2026'])
        ).filter(Boolean);

  const lastUpdated = article.lastUpdated || article.publishedAt || '2026-11';

  return {
    ...article,
    definitionLead,
    quickTakeaways,
    comparisonTable,
    faqs,
    seoKeywords,
    lastUpdated
  };
}

